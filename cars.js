export function carFromLocation() {
  const id = new URLSearchParams(location.search).get("car");
  return carById(id || (localStorage.getItem("car") || "458"));
}

export function rememberCar(id) {
  try {
    localStorage.setItem("car", id);
  } catch (e) {
    /* stockage indisponible : on ignore */
  }
}
